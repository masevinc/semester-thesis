def write_geo(path: Path, y1: float, y2: float) -> None:
    path.write_text(GEO_TEMPLATE.format(y1=y1, y2=y2))


def run_gmsh(gmsh_cmd: str, geo: Path, su2: Path, dim: int = 2) -> subprocess.CompletedProcess:
    cmd = [gmsh_cmd, str(geo), f"-{dim}", "-o", str(su2)]
    return subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)


def generate(args: argparse.Namespace) -> List[RampSample]:
    out_dir = Path(args.out_dir)
    geo_dir = out_dir / "geo_files"
    su2_dir = out_dir / "su2_meshes"

    for d in (out_dir, geo_dir, su2_dir):
        d.mkdir(parents=True, exist_ok=True)

    rng = random.Random(args.seed)

    samples: List[RampSample] = []
    for _ in range(args.n):
        y1, y2 = sample_pair(rng, args.y1_min, args.y1_max, args.delta, args.precision)
        geo_name = f"double_ramp_{y1}_{y2}.geo"
        su2_name = f"double_ramp_{y1}_{y2}.su2"
        geo_path = geo_dir / geo_name
        su2_path = su2_dir / su2_name
        sample = RampSample(y1, y2, geo_path, su2_path)

        if su2_path.exists() and not args.overwrite:
            sample.skipped = True
            samples.append(sample)
            continue

        # Write .geo
        write_geo(geo_path, y1, y2)
        # Invoke gmsh
        proc = run_gmsh(args.gmsh, geo_path, su2_path, dim=args.dim)
        if proc.returncode != 0 or not su2_path.exists():
            sample.error = f"gmsh failed (code={proc.returncode}) stderr: {proc.stderr.strip()}"
        else:
            sample.generated = True
        samples.append(sample)

    return samples


def summarize(samples: List[RampSample]) -> str:
    gen = sum(1 for s in samples if s.generated)
    skip = sum(1 for s in samples if s.skipped)
    err = sum(1 for s in samples if s.error and not s.generated)
    unique_pairs = {(s.y1, s.y2) for s in samples}
    lines = [
        "Generation summary:",
        f"  Total requested: {len(samples)}",
        f"  Unique parameter pairs: {len(unique_pairs)}",
        f"  Generated: {gen}",
        f"  Skipped (existing): {skip}",
        f"  Errors: {err}",
    ]
    if err:
        lines.append("  Error details (first 5):")
        for s in [s for s in samples if s.error][:5]:
            lines.append(f"    y1={s.y1} y2={s.y2}: {s.error}")
    return "\n".join(lines)


