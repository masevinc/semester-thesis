def sample_pair(rng: random.Random, y1_min: float, y1_max: float, delta: float, precision: int = 4) -> tuple[float, float]:
    y1 = round(rng.uniform(y1_min, y1_max), precision)
    lower_y2 = max(0.0, y1 - delta)
    upper_y2 = y1 + delta
    y2 = round(rng.uniform(lower_y2, upper_y2), precision)
    return y1, y2


